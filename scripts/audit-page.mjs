// Generate the audit record and the decisions page from docs/research/audit-<date>.json.
//
//   node scripts/audit-page.mjs            writes docs/research/audit-<date>.md and
//                                          .cache/audit-<date>/{index.html,area.css}
//   node scripts/audit-page.mjs --check    fails if the committed .md is out of date
//
// The JSON is the source of truth: finding status, owner picks and decisions change there.
// The page keeps Area's stylesheet as a separate file, so publish it with
// `files: { "area.css": ".cache/audit-<date>/area.css" }` rather than inlining it.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DATE = "2026-09-29";
const SRC = `${ROOT}docs/research/audit-${DATE}`;
const OUT = `${ROOT}.cache/audit-${DATE}`;
const check = process.argv.includes("--check");

const d = JSON.parse(readFileSync(`${SRC}.json`, "utf8"));
const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : "");
const by = (list, k) => list.reduce((a, x) => ((a[x[k]] = (a[x[k]] || 0) + 1), a), {});

const findings = d.findings;
const fixes = findings.filter((f) => f.type === "FIX" && !["rule", "call"].includes(f.route));
const choices = d.rules.flatMap((r) => r.choices);
const picked = [...choices, ...d.calls].filter((c) => c.pick).length;
const status = by(findings, "status");
const openFixes = fixes.filter((f) => f.status !== "done").length;

// ---- Markdown record --------------------------------------------------------
const routeName = { fix: "clear fix", rule: "system rule", call: "family call", drift: "docs drift", hygiene: "gallery hygiene", report: "report only" };
const md = [];
md.push(`# Audit ${DATE}`, "");
md.push(`Generated by \`scripts/audit-page.mjs\` from \`audit-${DATE}.json\`; edit the JSON, then rerun. Evidence for every finding is in [\`audit-${DATE}/reports/\`](audit-${DATE}/reports/).`, "");
md.push(d.about, "");
md.push("## Where it stands", "");
md.push(`- ${findings.length} findings: ${status.done || 0} done, ${status.partly || 0} partly, ${status.open || 0} open.`);
md.push(`- ${d.rules.length} system rules (${choices.length} choices) and ${d.calls.length} family calls; ${picked} picked by the owner.`);
md.push(`- ${fixes.length} clear fixes, ${openFixes} open; ${d.drift.filter((x) => x.status !== "done").length} docs drift rows open.`, "");
md.push("Workflow (owner, 2026-09-29): one phase per session. The owner picks, then a session implements about ten fixes or three rules, updates docs, sets status here and regenerates the page.", "");
md.push("## Sessions", "", "| Session | Date | Branch | Summary |", "|---|---|---|---|");
for (const s of d.sessions) md.push(`| ${s.id} | ${s.date} | \`${s.branch}\` | ${cell(s.summary)} |`);
md.push("", "## Owner decisions", "", "| ID | Date | Decision | Status |", "|---|---|---|---|");
for (const x of d.decisions) md.push(`| ${x.id} | ${x.date} | **${cell(x.title)}.** ${cell(x.decision)} | ${x.status}${x.resolved ? ` · ${x.resolved}` : ""} |`);

md.push("", "## System rules", "");
for (const r of d.rules) {
  md.push(`### ${r.id} ${r.title}`, "");
  md.push(`${cap(r.severity)} · ${r.status}${r.resolved ? ` · ${r.resolved}` : ""}${r.note ? ` (${r.note})` : ""} · findings ${r.sources.flatMap((s) => s.match(/[A-H]-\d+/g) || []).join(", ")}`, "");
  md.push(r.what, "");
  for (const c of r.choices) {
    md.push(`**${c.id} ${c.title}** (recommended ${c.rec}${c.pick ? `; owner picked **${c.pick}**` : ""})`, "");
    for (const [k, v] of c.opts) md.push(`- ${k}: ${v}`);
    if (c.note) md.push(`- Owner note: ${c.note}`);
    md.push("");
  }
  if (r.why) md.push(r.why, "");
}

md.push("## Family calls", "");
for (const g of [...new Set(d.calls.map((c) => c.group))]) {
  md.push(`### ${g}`, "");
  for (const c of d.calls.filter((x) => x.group === g)) {
    md.push(`**${c.id} ${c.title}** (${c.severity}; recommended ${c.rec}${c.pick ? `; owner picked **${c.pick}**` : ""})`, "");
    md.push(c.what, "");
    for (const [k, v] of c.opts) md.push(`- ${k}: ${v}`);
    if (c.note) md.push(`- Owner note: ${c.note}`);
    md.push("");
  }
}

md.push("## Findings", "", "Route says where a finding is settled: a clear fix, a system rule card, a family call, the docs drift list, gallery hygiene, or the report alone.", "");
md.push("| ID | Families | Severity | Type | Route | Status | Finding |", "|---|---|---|---|---|---|---|");
for (const f of findings) {
  const route = routeName[f.route] + (f.rules ? ` (${f.rules.join(", ")})` : "");
  const st = f.status + (f.resolved ? ` · ${f.resolved}` : "") + (f.note ? ` (${f.note})` : "");
  md.push(`| ${f.id} | ${cell(f.families)} | ${f.severity} | ${f.type} | ${route} | ${cell(st)} | ${cell(f.summary || f.title)} |`);
}
md.push("", "## Docs drift", "", "| Where | Says | Now | Status |", "|---|---|---|---|");
for (const x of d.drift) md.push(`| ${cell(x.where)} | ${cell(x.says)} | ${cell(x.now)} | ${x.status} |`);
md.push("", "## Checks at audit time", "", "| Command | Result | Note |", "|---|---|---|");
for (const x of d.checks) md.push(`| \`${cell(x.command)}\` | ${x.result} | ${cell(x.note)} |`);
const mdText = md.join("\n") + "\n";

if (check) {
  const cur = existsSync(`${SRC}.md`) ? readFileSync(`${SRC}.md`, "utf8") : "";
  if (cur !== mdText) { console.error(`audit-${DATE}.md is out of date; run node scripts/audit-page.mjs`); process.exit(1); }
  console.log(`audit-${DATE}.md is current`);
  process.exit(0);
}
writeFileSync(`${SRC}.md`, mdText);

// ---- Decisions page ---------------------------------------------------------
const tpl = (n) => readFileSync(`${SRC}/page/${n}`, "utf8");
const chooseHtml = (c) =>
  `<div class="choose" data-dec="${esc(c.id)}" data-title="${esc(c.title)}" data-rec="${esc(c.rec)}"${c.pick ? ` data-pick="${esc(c.pick)}"` : ""} data-opts='${JSON.stringify(c.opts).replace(/&/g, "&amp;").replace(/'/g, "&#39;")}'></div>`;
const statusTag = (r) =>
  r.status === "done" ? `<span class="tag-done">Done · ${esc(r.choices.map((c) => (r.choices.length > 1 ? `${c.id} ` : "") + c.pick).join(", "))} · ${esc(r.resolved || "")}</span>` : r.status === "decided" ? `<span class="tag-done">Owner pick · ${esc(r.choices.map((c) => (r.choices.length > 1 ? `${c.id} ` : "") + c.pick).join(", "))}</span>` : r.status === "partly" ? `<span class="tag-now" title="${esc(r.note)}">Partly settled</span>` : "";

const stats = `<div class="stats">
    <div class="stat"><b>58</b><span>families, all Complete</span></div>
    <div class="stat"><b>${findings.length}</b><span>findings from 8 audits</span></div>
    <div class="stat"><b>${d.rules.length}</b><span>system decisions</span></div>
    <div class="stat"><b>${d.calls.length}</b><span>family decisions</span></div>
    <div class="stat"><b>${fixes.length}</b><span>clear fixes</span></div>
    <div class="stat"><b>${status.done || 0}</b><span>findings done</span></div>
    <div class="stat"><b>${picked}</b><span>choices picked</span></div>
  </div>`;
const ledgerRows = d.decisions.map((x) =>
  `<div class="row"><div><b>${esc(x.title)}</b><p>${esc(x.decision)}</p></div><span class="${x.status === "done" ? "tag-done" : "tag-now"}">${x.status === "done" ? "Done" : "Open"}${x.resolved ? ` · ${esc(x.resolved)}` : ""}</span></div>`);
ledgerRows.push(`<div class="row"><div><b>Still open</b><p>${d.rules.filter((r) => r.status !== "done").length} system rules to implement (${d.rules.filter((r) => r.status === "open" || r.status === "partly").length} still undecided), ${d.calls.filter((c) => !c.pick).length} family calls undecided, ${openFixes} clear fixes and ${d.drift.filter((x) => x.status !== "done").length} docs drift rows.</p></div><span class="tag-now">${picked === choices.length + d.calls.length ? "Implementation next" : "Your picks next"}</span></div>`);
const ledger = `<div class="ledger">\n    ${ledgerRows.join("\n    ")}\n  </div>`;
const lede = `<p class="lede">Every family is owner-approved, so this pass looked across them: consistency between families, visual quality, agreement with DESIGN_SYSTEM.md and the owner decisions in the handoff, and interaction and accessibility. Generated from <code>docs/research/audit-${DATE}.json</code>; specimens render with Area's current stylesheet, so fixed items show their fixed state.</p>`;

const missing = [];
const body = tpl("body.html")
  .replace("{{stats}}", () => stats)
  .replace("{{ledger}}", () => ledger)
  .replace("{{lede}}", () => lede)
  .replace(/\{\{choose:([^}]+)\}\}/g, (_, id) => { const c = choices.find((x) => x.id === id); if (!c) { missing.push(id); return ""; } return chooseHtml(c); })
  .replace(/\{\{status:([^}]+)\}\}/g, (_, id) => { const r = d.rules.find((x) => x.id === id); return r ? statusTag(r) : ""; });
if (missing.length) throw new Error("Missing choices: " + missing.join(", "));

const FIXES = fixes.map((f) => [f.id, f.families, f.severity, f.category, f.summary || f.title, f.status, f.resolved || "", f.note || ""]);
const DRIFT = d.drift.map((x) => [x.where, x.says, x.now]);
const CHECKS = d.checks.map((x) => [x.command, x.result, x.note]);
const SMALL = d.calls.map((c) => ({ id: c.id, group: c.group, title: c.title, sev: c.severity, what: c.what, opts: c.opts, rec: c.rec, pick: c.pick }));
const json = (v) => JSON.stringify(v).replace(/</g, "\\u003c");
const script = `var FIXES = ${json(FIXES)};\nvar DRIFT = ${json(DRIFT)};\nvar CHECKS = ${json(CHECKS)};\nvar SMALL = ${json(SMALL)};\n${tpl("page.js")}`;

const html = `<meta charset="utf-8">
<title>Area Audit Decisions</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="area.css">
<style>
${tpl("page.css")}</style>
${body}<script>
${script}</script>
`;

// The artifact CSP blocks jsDelivr fonts; Geist comes from Google Fonts instead.
const css = readFileSync(`${ROOT}packages/styles/dist/area.css`, "utf8").replace(/@font-face\s*\{[^}]*cdn\.jsdelivr\.net[^}]*\}/g, "");
mkdirSync(OUT, { recursive: true });
writeFileSync(`${OUT}/index.html`, html);
writeFileSync(`${OUT}/area.css`, css);
console.log(`audit-${DATE}.md, page ${(html.length / 1024).toFixed(0)} KB + area.css ${(css.length / 1024).toFixed(0)} KB in .cache/audit-${DATE}/`);
