// Generates levers.css: materials as separate levers (owner, 2026-10-17: "breaking down materials into the individual
// levers is better for control, similar to how surface is created with a bunch of different controls").
//
// Each lever is one number, 0 (off) to 8, like Elevation and Layers, with the part groups it reaches (like the Pills
// setting). One light angle drives every direction. A "material" is a saved set of lever values.
//
// Part groups and their default strength come from 29-scope (platforms, libraries and historic styles): primary
// controls carry a material at full strength; secondary controls, solid badges, wells and selected rows take an echo
// at half; ghost and text parts take none. Pressed parts flip to recessed; disabled parts drop the material.
// Research only. node docs/research/astra/materials/27-levers/gen-levers.mjs
import { writeFileSync } from "node:fs";
const here = new URL(".", import.meta.url).pathname;

// Part groups: [id, default scope (strength multiplier), concave?]
const ROLES = [["primary", 1, false], ["secondary", 0.5, false], ["marks", 0.5, false], ["wells", 0.5, true], ["selection", 0.5, true], ["surfaces", 1, false], ["overlays", 1, false], ["chrome", 1, false]];
const R = ROLES.map(r => r[0]);
// Which groups each lever reaches by default (29-scope: what the evidence paints where).
const TARGETED = {
  gradient: ["primary"],
  sheen: ["primary"],
  // Glass reaches cards and overlays both (owner, 2026-10-17), and chrome, where platforms put it first (29-scope).
  transparency: ["surfaces", "overlays", "chrome"],
  frost: ["surfaces", "overlays", "chrome"],
  stroke: ["primary", "secondary", "marks"],
  inner: ["primary", "wells"],
  catch: ["primary", "wells"],
  emboss: ["primary"],
  contact: ["primary", "secondary"],
};
const D = "var(--lv-dark)";                       // 0 light, 1 dark
const mixD = (light, dark) => `calc(${light} + (${dark} - ${light}) * ${D})`;
const alpha = (rgb, a) => `rgb(${rgb} / calc(${a}))`;

let css = `/* GENERATED by gen-levers.mjs. Materials as levers (27-levers/README.md), scoped by part group (29-scope). */
[data-lv] {
  /* ---- Inputs: each lever 0–8; style and shape switches are 0/1 gates; scopes are 0–1. ---- */
  --lv-angle: 0deg;
  --lv-gradient: 0; --lv-gradient-radial: 0; --lv-gradient-accent: 0; --lv-gradient-centre: 0; --lv-gradient-away: 0;
  --lv-sheen: 0; --lv-sheen-band: 0;
  --lv-transparency: 0; --lv-frost: 0; --lv-holds-icons: 0; --lv-holds-none: 0;
  --lv-stroke: 0; --lv-stroke-solid: 0; --lv-stroke-lit: 0; --lv-stroke-gradient: 0; --lv-stroke-double: 0; --lv-stroke-neutral: 0;
  --lv-inner: 0; --lv-softness: 0; --lv-catch: 0;
  --lv-emboss: 0;
  --lv-contact: 0; --lv-glow: 0; --lv-grain: 0; --lv-page-glow: 0;
${Object.entries(TARGETED).map(([l, t]) => "  " + R.map(r => `--lv-${l}-${r}: ${t.includes(r) ? 1 : 0};`).join(" ")).join("\n")}
  ${ROLES.map(([r, scope]) => `--lv-scope-${r}: ${scope};`).join(" ")}
  --lv-dark: 0;

  /* ---- Light: unit offsets (shadow side = +). ---- */
  --lv-lx: calc(-1 * sin(var(--lv-angle)));
  --lv-ly: cos(var(--lv-angle));
  /* Where a radial gradient centres: toward the light (1), the middle (0) or away (-1; Aero's glow from below). */
  --lv-from: calc(1 - var(--lv-gradient-centre) - 2 * var(--lv-gradient-away));
  /* The least opacity, by what see-through parts hold (28-recipes): text 4.5:1 over any backdrop (0.56 / 0.62);
     accent icons 3:1 (0 / 0.71); empty chrome none. */
  --lv-floor: calc(${mixD("0.56", "0.62")} * (1 - var(--lv-holds-icons) - var(--lv-holds-none)) + ${mixD("0", "0.71")} * var(--lv-holds-icons));
  --lv-lit-color: color-mix(in oklab, white, var(--area-accent-solid) calc(var(--lv-gradient-accent) * 55%));
`;
for (const [r, , concave] of ROLES) {
  const s = l => TARGETED[l] ? `calc(var(--lv-${l}) / 8 * var(--lv-${l}-${r}) * var(--lv-scope-${r}))` : `calc(var(--lv-${l}) / 8 * var(--lv-scope-${r}))`;
  const flip = concave ? -1 : 1;
  css += `
  /* ---- ${r}${concave ? " (concave: gradients and shading reverse)" : ""} ---- */
  --${r}-grad: ${s("gradient")}; --${r}-sheen: ${s("sheen")}; --${r}-stroke: ${s("stroke")};
  --${r}-inner: ${s("inner")}; --${r}-emboss: ${s("emboss")}; --${r}-catch: ${s("catch")}; --${r}-contact: ${s("contact")};
  --${r}-alpha: calc(1 - ${s("transparency")} * (1 - var(--lv-floor)));
  --${r}-frost-n: ${s("frost")};
  --${r}-frost: calc(var(--${r}-frost-n) * 32px);
  --${r}-px: calc(50% - var(--lv-lx) * 45% * var(--lv-from) * ${flip});
  --${r}-py: calc(50% - var(--lv-ly) * 45% * var(--lv-from) * ${flip});
  --${r}-img:
    linear-gradient(calc(var(--lv-angle) + ${concave ? "0deg" : "180deg"}), color-mix(in srgb, var(--lv-lit-color) calc(var(--${r}-grad) * (1 - var(--lv-gradient-radial)) * ${mixD("45%", "24%")}), transparent), transparent 50%, ${alpha("0 0 0", `var(--${r}-grad) * (1 - var(--lv-gradient-radial)) * ${mixD("0.22", "0.45")}`)}),
    radial-gradient(130% 110% at var(--${r}-px) var(--${r}-py), color-mix(in srgb, var(--lv-lit-color) calc(var(--${r}-grad) * var(--lv-gradient-radial) * ${mixD("55%", "28%")}), transparent), transparent 60%, ${alpha("0 0 0", `var(--${r}-grad) * var(--lv-gradient-radial) * ${mixD("0.18", "0.4")}`)}),
    linear-gradient(calc(var(--lv-angle) + 180deg), ${alpha("255 255 255", `var(--${r}-sheen) * (1 - var(--lv-sheen-band)) * ${mixD("0.7", "0.22")}`)}, transparent 62%),
    linear-gradient(calc(var(--lv-angle) + 180deg), ${alpha("255 255 255", `var(--${r}-sheen) * var(--lv-sheen-band) * ${mixD("0.55", "0.2")}`)} 0 49%, transparent 50%);
  --${r}-stroke-img: linear-gradient(calc(var(--lv-angle) + 180deg), ${alpha("255 255 255", `var(--${r}-stroke) * var(--lv-stroke-gradient) * ${mixD("1.8", "0.5")}`)}, transparent 55%, ${alpha("0 0 0", `var(--${r}-stroke) * var(--lv-stroke-gradient) * ${mixD("0.5", "1.2")}`)});
  --${r}-shadow:
    0 0 0 ${mixD("1px", "1.5px")} ${alpha("0 0 0", `var(--${r}-stroke) * min(1, var(--lv-stroke-solid) + var(--lv-stroke-double)) * var(--lv-stroke-neutral) * ${mixD("0.32", "2")}`)},
    inset calc(var(--lv-lx) * -1px) calc(var(--lv-ly) * ${mixD("1px", "1.5px")}) 0 0 ${alpha("255 255 255", `var(--${r}-stroke) * var(--lv-stroke-lit) * ${mixD("1.8", "0.3")}`)},
    inset 0 0 0 1px ${alpha("255 255 255", `var(--${r}-stroke) * var(--lv-stroke-double) * ${mixD("1.6", "0.3")}`)},
    inset calc(var(--lv-lx) * -1 * (1px + var(--lv-softness) * 0.25px)) calc(var(--lv-ly) * (1px + var(--lv-softness) * 0.25px)) calc(var(--lv-softness) * 0.75px) 0 ${concave
      ? alpha("0 0 0", `var(--${r}-inner) * ${mixD("0.22", "0.75")}`)
      : alpha("255 255 255", `var(--${r}-inner) * ${mixD("1.2", "0.25")}`)},
    inset calc(var(--lv-lx) * (1px + var(--lv-softness) * 0.25px)) calc(var(--lv-ly) * -1 * (1px + var(--lv-softness) * 0.25px)) calc(var(--lv-softness) * 0.75px) 0 ${concave
      ? alpha("255 255 255", "0")
      : alpha("0 0 0", `var(--${r}-inner) * ${mixD("0.3", "0.6")}`)},
    inset calc(var(--lv-lx) * 3px) calc(var(--lv-ly) * -3px) 2px -1px ${alpha("255 255 255", `min(1, var(--${r}-catch) * ${mixD("1.4", "0.9")})`)},
    calc(var(--lv-lx) * -1 * var(--${r}-emboss) * 5px) calc(var(--lv-ly) * -1 * var(--${r}-emboss) * 5px) calc(var(--${r}-emboss) * 14px) 0 ${alpha("255 255 255", `min(1, var(--${r}-emboss) * 2) * ${mixD("0.95", "0.05")}`)},
    calc(var(--lv-lx) * var(--${r}-emboss) * 5px) calc(var(--lv-ly) * var(--${r}-emboss) * 5px) calc(var(--${r}-emboss) * 14px) 0 ${alpha("0 0 0", `min(1, var(--${r}-emboss) * 2) * ${mixD("0.14", "0.65")}`)},
    calc(var(--lv-lx) * -1 * var(--${r}-contact) * ${mixD("4px", "8px")}) calc(var(--lv-ly) * var(--${r}-contact) * ${mixD("4px", "8px")}) calc(var(--${r}-contact) * ${mixD("8px", "14px")}) 0 ${alpha("0 0 0", `var(--${r}-contact) * ${mixD("0.2", "0.4")}`)};
`;
}
css += `
  --lv-glow-shadow: 0 0 calc(var(--lv-glow) * 2.5px) calc(var(--lv-glow) * 0.4px) color-mix(in oklab, var(--area-accent-solid) calc(var(--lv-glow) * 11%), transparent);
}
[data-area-theme="dark"][data-lv], [data-area-theme="dark"] [data-lv] { --lv-dark: 1; }
[data-area-theme="light"] [data-lv] { --lv-dark: 0; }
`;

// Painted receivers: fill (by state), frame colour and own shadow (kept last). Tone ring: the fill, darker.
const RECEIVERS = [
  { role: "primary", sel: ".area-button.area-button--solid", fill: ["var(--_bg)", "var(--_bg-hover)", "var(--_bg-active)"], frame: "var(--_border)", own: "var(--lv-glow-shadow)", states: true, wash: true },
  { role: "primary", sel: ".area-segmented__item[data-selected]", fill: ["light-dark(var(--area-bg-surface), var(--area-bg-component-active))"], frame: "var(--area-edge-selected)", own: "var(--area-shadow-control)" },
  { role: "secondary", sel: ".area-button:is(.area-button--outline, .area-button--soft)", fill: ["var(--_bg)", "var(--_bg-hover)", "var(--_bg-active)"], frame: "var(--_border)", own: "", states: true, wash: true },
  { role: "marks", sel: ".area-badge--solid", fill: ["var(--_bg)"], frame: "var(--_border, transparent)", own: "" },
  { role: "wells", sel: ".area-input:not(:focus-within)", fill: ["var(--_bg)"], frame: "var(--_border)", own: "" },
  { role: "selection", sel: ":is(.area-menu__item[data-selected], .area-nav__item[aria-current]:not([aria-current=\"false\"]))", fill: ["var(--area-bg-component-active)"], frame: "transparent", own: "" },
  { role: "surfaces", sel: ".area-card", fill: ["var(--area-bg-surface)"], frame: "var(--_card-edge)", own: "var(--area-shadow-edge), var(--_card-shadow)" },
  { role: "overlays", sel: ":is(.area-menu, .area-popover, .area-toast)", fill: ["var(--area-bg-surface)"], frame: "var(--area-border-float)", own: "var(--area-shadow-edge), var(--_elevation)" },
  // Chrome: title bar, toolbar and sidebar regions (marked data-lv-chrome in the prototype; .area-titlebar in Area).
  // Its body takes glass and a rim only; its buttons stay ghost (29-scope, rule 7).
  { role: "chrome", sel: ":is([data-lv-chrome], .area-titlebar)", fill: ["var(--lv-chrome-fill, var(--area-bg-page))"], frame: "transparent", own: "" },
];
const list = (...xs) => xs.filter(Boolean).join(", ");
for (const r of RECEIVERS) {
  const G = r.role;
  const fillLayer = f => `linear-gradient(color-mix(in srgb, ${f} calc(var(--${G}-alpha) * 100%), transparent), color-mix(in srgb, ${f} calc(var(--${G}-alpha) * 100%), transparent))`;
  const frameLayer = `linear-gradient(color-mix(in srgb, ${r.frame} calc(var(--lv-stroke-gradient) * 100%), transparent), color-mix(in srgb, ${r.frame} calc(var(--lv-stroke-gradient) * 100%), transparent))`;
  const bg = (f, wash, clip) => `background: var(--${G}-img)${wash ? `, ${wash}` : ""}, ${fillLayer(f)} padding-box, var(--${G}-stroke-img) ${clip}, ${frameLayer} ${clip}; background-origin: border-box;`;
  const toneRing = `0 0 0 ${mixD("1px", "1.5px")} color-mix(in srgb, color-mix(in oklab, ${r.fill[0]}, black 30%) calc(min(1, var(--${G}-stroke) * 2 * min(1, var(--lv-stroke-solid) + var(--lv-stroke-double)) * (1 - var(--lv-stroke-neutral))) * 100%), transparent)`;
  const rest = r.wash ? "var(--_wash-rest, linear-gradient(transparent, transparent))" : "";
  css += `
[data-lv] ${r.sel} {
  ${bg(r.fill[0], rest, "border-box")}
  border-color: color-mix(in srgb, ${r.frame} calc((1 - var(--lv-stroke-gradient)) * 100%), transparent);
  box-shadow: ${list(toneRing, `var(--${G}-shadow)`, r.own)};
  backdrop-filter: blur(var(--${G}-frost)) saturate(calc(100% + var(--${G}-frost-n) * 50%));
}
@supports (background-clip: border-area) { [data-lv] ${r.sel} { ${bg(r.fill[0], rest, "border-area")} } }`;
  if (r.states) css += `
@media (hover: hover) { [data-lv] ${r.sel}:hover:not(:disabled) { ${bg(r.fill[1], "var(--_wash-hover)", "border-box")} } }
@supports (background-clip: border-area) { @media (hover: hover) { [data-lv] ${r.sel}:hover:not(:disabled) { ${bg(r.fill[1], "var(--_wash-hover)", "border-area")} } } }
/* Pressed flips raised to recessed (daisyUI :active, neumorphism). */
[data-lv] ${r.sel}:active:not(:disabled) { background: ${fillLayer(r.fill[2])}; box-shadow: ${toneRing}, inset 0 1px 2px ${alpha("0 0 0", `(var(--${G}-inner) + var(--${G}-stroke)) * ${mixD("0.3", "0.6")}`)}; }`;
}
css += `
/* Shadow-only parts at full strength: thumbs and ticked boxes carry the material (daisyUI, Untitled UI, Aqua). */
[data-lv] :is(.area-switch__thumb, .area-checkbox__control:checked, .area-radio__control:checked) { box-shadow: var(--primary-shadow), var(--area-shadow-control); background-image: var(--primary-img); }
[data-lv] .area-slider__control::-webkit-slider-thumb { box-shadow: var(--primary-shadow), var(--area-shadow-control); }
/* Wells: fields, tracks, unticked boxes. */
[data-lv] :is(.area-switch__track, .area-segmented, .area-progress, .area-checkbox__control:not(:checked), .area-radio__control:not(:checked)) { box-shadow: var(--wells-shadow); background-image: var(--wells-img); }
[data-lv] .area-input:focus-within { box-shadow: 0 0 0 var(--area-field-focus-halo-width) var(--_focus-halo), var(--wells-shadow); }
[data-lv] .area-slider__control::-webkit-slider-runnable-track { box-shadow: var(--wells-shadow); }
[data-lv] .area-switch__track[data-checked] { box-shadow: var(--wells-shadow), var(--lv-glow-shadow); }
/* Disabled parts drop the material. */
[data-lv] :is(.area-button, .area-input, .area-switch, .area-segmented__item, .area-checkbox__control, .area-radio__control):is(:disabled, [data-disabled]) { box-shadow: none; background-image: none; }
/* Reduced transparency and forced colours: opaque, no blur (D7). */
@media (prefers-reduced-transparency: reduce) { [data-lv] { --lv-transparency: 0; --lv-frost: 0; } }
[data-lv][data-lv-opaque] { --lv-transparency: 0 !important; --lv-frost: 0 !important; }
@media (forced-colors: active) { [data-lv] * { backdrop-filter: none !important; background-image: none !important; } }
`;
writeFileSync(here + "levers.css", css);
console.log("levers.css", css.length);
