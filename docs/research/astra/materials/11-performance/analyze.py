#!/usr/bin/env python3
"""Validate aggregate evidence and reproduce the compact case tables. No browser automation."""
import argparse, hashlib, json, statistics
from pathlib import Path
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[4]
def median(xs): return statistics.median(xs) if xs else None
def baseline(c):
 b={k:v for k,v in c.items() if k!='id'}
 if c['family']=='blur': b['radius']=0
 elif c['family']=='shadow': b['layers']=0
 elif c['family']=='refraction': b['scale']=0
 elif c['family']=='grain': b['kind']='none'
 elif c['family']=='stroke': b['kind']='solid'
 return b
def key(c): return tuple(sorted((k,v) for k,v in c.items() if k!='id'))
def fmt(n): return '—' if n is None else f'{n:.2f}'
def build():
 output={'schema':1,'metric':'median of valid trial p95 rAF intervals, milliseconds','runs':[]}
 md=['# Measured frame cadence', '', 'Generated by [analyze.py](analyze.py). Values are milliseconds unless marked %. Each case has three shuffled repetitions; valid trials must remain visible, focused, unresized and unaborted, with a valid cadence calibration. p95 is the median of trial p95s; range is the min–max of those p95s. Δ compares with the same-family/count/row/mode baseline in the same repeat. Neither Δ nor rAF cadence is GPU render time. The slow-interval proxy is intervals >1.5× that repeat’s calibrated period, pooled over valid trials. All original aggregate trials remain in the evidence JSON.', '']
 for path in sorted((HERE/'results').glob('*.json')):
  assert path.stat().st_size<1_000_000
  d=json.loads(path.read_text()); assert d['schema']==1
  assert len(d['cases'])==126 and len({c['id'] for c in d['cases']})==126
  assert d['complete'] and len(d['trials'])==378, f'{path.name}: incomplete'
  assert {(t['caseId'],t['repeat']) for t in d['trials']}=={(c['id'],r) for c in d['cases'] for r in range(3)}
  for f,digest in d['fixture_sha256'].items():
   assert hashlib.sha256((HERE/f).read_bytes()).hexdigest()==digest, f'{path}: fixture changed: {f}'
  calibrated={c['repeat']:c for c in d['calibrations']}; assert len(calibrated)==3
  valid=[t for t in d['trials'] if t['valid'] and calibrated[t['repeat']]['valid']]
  assert all(t['interval']['samples']>0 and t['elapsed']>=d['config']['sampleMs'] for t in valid)
  rows=[]; indexed={key(c):c for c in d['cases']}
  for c in d['cases']:
   ts=[t for t in valid if t['caseId']==c['id']]
   b=indexed[key(baseline(c))]
   bt={t['repeat']:t for t in valid if t['caseId']==b['id']}
   ps=[t['interval']['p95'] for t in ts]
   count=sum(t['interval']['samples'] for t in ts)
   rows.append({'case':c,'baseline':b['id'],'valid_repeats':len(ts),'p50':median([t['interval']['p50'] for t in ts]),'p95':median(ps),'p95_range':[min(ps),max(ps)] if ps else None,'paired_repeats':sum(t['repeat'] in bt for t in ts),'delta_p95_paired':median([t['interval']['p95']-bt[t['repeat']]['interval']['p95'] for t in ts if t['repeat'] in bt]),'slow_interval_pct':100*sum(t['interval']['over1_5period'] for t in ts)/count if count else None,'over50_count':sum(t['interval']['over50'] for t in ts),'max_interval':max([t['interval']['max'] for t in ts],default=None),'callback_p95':median([t['callback']['p95'] for t in ts]),'samples':count})
  run={'label':d['label'],'evidence':'results/'+path.name,'evidence_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'environment':d['environment'],'started':d['started'],'finished':d['finished'],'valid':len(valid),'excluded':len(d['trials'])-len(valid),'calibrated_periods':[c['period'] for c in d['calibrations']],'cases':rows}
  output['runs'].append(run)
  md+=['## '+d['label'], '', f"Evidence: [{path.name}](results/{path.name}). **{len(valid)}/378 valid trials**. Calibration medians: {', '.join(fmt(x) for x in run['calibrated_periods'])} ms. Viewport {d['environment']['viewport']}; DPR {d['environment']['dpr']}. Each case ID maps to its full recipe and three original aggregates in the JSON; no trial has been deleted.", '', '| ID | Family / parameters | Mode | Valid n / intervals | p50 | p95 (range) | Paired Δp95 (n) | Slow % | >50ms count | JS p95 |', '| --- | --- | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: |']
  for r in rows:
   c=r['case'];desc=', '.join(f'{k}={v}' for k,v in c.items() if k not in ('family','mode','id'))
   rg='–'.join(fmt(x) for x in r['p95_range']) if r['p95_range'] else '—'
   md.append(f"| {c['id']} | {c['family']}: {desc} | {c['mode']} | {r['valid_repeats']} / {r['samples']} | {fmt(r['p50'])} | {fmt(r['p95'])} ({rg}) | {fmt(r['delta_p95_paired'])} ({r['paired_repeats']}) | {fmt(r['slow_interval_pct'])} | {r['over50_count']} | {fmt(r['callback_p95'])} |")
  md+=['']
 return {'summary.json':json.dumps(output,indent=2)+'\n','results.md':'\n'.join(md).rstrip()+'\n'}
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 files=build();assert len(json.loads(files['summary.json'])['runs'])>=2, 'Need both browser runs'
 for f,text in files.items():
  assert len(text.encode())<1_000_000
  if a.check: assert (HERE/f).read_text()==text, f+' differs'
  else: (HERE/f).write_text(text)
 for p in HERE.rglob('*'):
  if p.is_file(): assert p.stat().st_size<1_000_000, str(p)
 print('Verified complete run structure, fixtures, aggregates, deterministic summaries and file sizes.')
