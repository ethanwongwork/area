export const GALLERY_SPECIMENS = gallerySpecimenTable();
/**
 * A family's tiles, without verification fixtures or theme, stress and RTL checks.
 * hasDemo(name) says whether the registry has a demo by that name (the Gallery<Name> fallback).
 */
export function componentSpecimens(component, hasDemo) {
  const fallbackName = `Gallery${component.exportName ?? component.name.replaceAll(" ", "")}`;
  return (GALLERY_SPECIMENS[component.slug] ??
    [{ id: "default", title: "Default", demo: hasDemo(fallbackName) ? fallbackName : component.examples[0].demo }])
    .filter(example => !example.verification && !/^(theme-|stress-|rtl$)/.test(example.id));
}

