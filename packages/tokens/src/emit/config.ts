import { AXES, defaultPresetOf, assertAxisIntegrity } from '../axes/registry.ts';
import { PILL_SHAPES, DEFAULT_PILLS } from '../axes/pills.ts';
import { UI_SHORTHAND } from '../axes/ui-scale.ts';
import { DEFAULT_MATERIAL, MATERIAL_BUNDLES, MATERIAL_LEVERS, MATERIAL_STROKE_STYLES, MATERIAL_SWITCHES, leverSteps } from '../axes/material.ts';

/** Small, DOM-free public configuration helpers generated from the actual registry. */
export function emitConfig(): string {
  assertAxisIntegrity();
  const presets=Object.fromEntries(AXES.map(axis=>[axis.id,axis.presets.map(p=>p.id)]));
  const defaults=Object.fromEntries(AXES.map(axis=>[axis.id,defaultPresetOf(axis).id]));
  const levers=MATERIAL_LEVERS.map(l=>({id:l.id,label:l.label,group:l.group,hint:l.hint,steps:leverSteps(l.id)}));
  const switches=MATERIAL_SWITCHES.map(s=>({id:s.id,label:s.label,lever:s.lever,options:s.options.map(o=>({value:o[0],label:o[1]}))}));
  const strokes=MATERIAL_STROKE_STYLES.map(s=>({id:s.id,label:s.label}));
  const bundles=Object.fromEntries(Object.entries(MATERIAL_BUNDLES).map(([id,b])=>[id,{label:b.label,description:b.description,levers:b.levers??{},switches:b.switches??{},stroke:b.stroke??[],layers:b.layers??{}}]));
  return `// Generated by Area. Do not edit.
export const AXIS_PRESETS = Object.freeze(Object.fromEntries(Object.entries(${JSON.stringify(presets)}).map(([key,values])=>[key,Object.freeze(values)])));
export const DEFAULT_AXES = Object.freeze(${JSON.stringify(defaults)});
/** The former UI scale, kept as a shorthand for a type size and a density. */
export const UI_SHORTHAND = Object.freeze(${JSON.stringify(UI_SHORTHAND)});

export function mergeAxes(parent = DEFAULT_AXES, overrides = {}) {
  const result = { ...DEFAULT_AXES };
  for (const selection of [parent, overrides]) {
    if(selection === null || typeof selection !== "object" || Array.isArray(selection)) throw new TypeError("Area selections must be objects.");
    // \`ui\` first, so an explicit type or density in the same selection wins.
    const entries = Object.entries(selection).sort(([a], [b]) => (b === 'ui') - (a === 'ui'));
    for (const [axis, value] of entries) {
    if (axis === 'ui') {
      if (value === undefined) continue;
      if (!Object.hasOwn(UI_SHORTHAND, value)) throw new RangeError('Unknown Area preset: ui=' + value);
      Object.assign(result, UI_SHORTHAND[value]);
      continue;
    }
    if (!Object.hasOwn(AXIS_PRESETS, axis)) throw new RangeError('Unknown Area axis: ' + axis);
    if (value === undefined) continue;
    if (!AXIS_PRESETS[axis].includes(value)) throw new RangeError('Unknown Area preset: ' + axis + '=' + value);
    result[axis] = value;
  }
  }
  return Object.freeze(result);
}

/** Components that can draw a pill instead of the radius corner (axes/pills.ts), and the default pills. */
export const PILL_SHAPES = Object.freeze(${JSON.stringify(PILL_SHAPES.map(shape=>shape.id))});
export const DEFAULT_PILLS = Object.freeze(${JSON.stringify(DEFAULT_PILLS)});

/** The data-area-pills value for a list of pill shapes; unknown names throw. */
export function pillsAttribute(pills = DEFAULT_PILLS) {
  for (const pill of pills) if (!PILL_SHAPES.includes(pill)) throw new RangeError('Unknown Area pill shape: ' + pill);
  return [...new Set(pills)].join(' ');
}

/** Material (axes/material.ts): levers, one-of switches, stroke styles and bundles, for pickers. A bundle omits what it
 *  leaves at 0, at its first option or off. Select with data-area-material="<bundle>" and data-area-material-<id>. */
export const MATERIAL_LEVERS = Object.freeze(${JSON.stringify(levers)});
export const MATERIAL_SWITCHES = Object.freeze(${JSON.stringify(switches)});
export const MATERIAL_STROKE_STYLES = Object.freeze(${JSON.stringify(strokes)});
export const MATERIAL_BUNDLES = Object.freeze(${JSON.stringify(bundles)});
export const DEFAULT_MATERIAL = ${JSON.stringify(DEFAULT_MATERIAL)};

export function themeAttributes(selection = DEFAULT_AXES) {
  return Object.fromEntries(Object.entries(mergeAxes(DEFAULT_AXES, selection)).map(([axis,value])=>['data-area-'+axis,value]));
}
`;
}

export function emitConfigTypes(): string {
  return `// Generated from the Area registry. Do not edit.
export interface AxisSelection {
${AXES.map(axis=>`  ${/^[a-z]+$/.test(axis.id) ? axis.id : JSON.stringify(axis.id)}: ${axis.presets.map(p=>JSON.stringify(p.id)).join(' | ')};`).join('\n')}
  /** Shorthand for a type size and a density (the former UI scale): "compact" is type 12, Compact;
   *  "default" is type 14, Default. An explicit \`type\` or \`density\` wins. Never in a merged result. */
  ui?: ${Object.keys(UI_SHORTHAND).map(k=>JSON.stringify(k)).join(' | ')};
}
export declare const AXIS_PRESETS: Readonly<{ [K in keyof AxisSelection]: readonly AxisSelection[K][] }>;
export declare const DEFAULT_AXES: Readonly<AxisSelection>;
/** The former UI scale: a type size and a density in one word. */
export type UiShorthand = ${Object.keys(UI_SHORTHAND).map(k=>JSON.stringify(k)).join(' | ')};
export declare const UI_SHORTHAND: Readonly<Record<UiShorthand, { type: AxisSelection["type"]; density: AxisSelection["density"] }>>;
/** A selection: any axes, plus \`ui\`, the shorthand (an explicit type or density wins over it). */
export type AxisInput = Partial<AxisSelection>;
export declare function mergeAxes(parent?: AxisInput, overrides?: AxisInput): Readonly<AxisSelection>;
export type PillShape = ${PILL_SHAPES.map(shape=>JSON.stringify(shape.id)).join(' | ')};
export declare const PILL_SHAPES: readonly PillShape[];
export declare const DEFAULT_PILLS: readonly PillShape[];
export declare function pillsAttribute(pills?: readonly PillShape[]): string;
export interface MaterialLeverInfo { id: string; label: string; group: string; hint: string; steps: readonly number[] }
export interface MaterialSwitchInfo { id: string; label: string; lever: string; options: ReadonlyArray<{ value: string; label: string }> }
export interface MaterialBundleInfo { label: string; description: string; levers: Readonly<Record<string, number>>; switches: Readonly<Record<string, string>>; stroke: readonly string[]; layers: Readonly<Record<string, string>> }
export declare const MATERIAL_LEVERS: readonly MaterialLeverInfo[];
export declare const MATERIAL_SWITCHES: readonly MaterialSwitchInfo[];
export declare const MATERIAL_STROKE_STYLES: ReadonlyArray<{ id: string; label: string }>;
export declare const MATERIAL_BUNDLES: Readonly<Record<string, MaterialBundleInfo>>;
export declare const DEFAULT_MATERIAL: string;
export declare function themeAttributes(selection?: AxisInput): { [K in Exclude<keyof AxisSelection, "ui"> as \`data-area-\${K}\`]: AxisSelection[K] };
`;
}
